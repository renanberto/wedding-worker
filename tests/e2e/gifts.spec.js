import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
test('presentes: cadastro, escolha, confirmação explícita e liberação na demonstração', async ({ page }) => {
  test.skip(process.env.E2E_SITE !== 'demo-moderno', 'O fluxo usa apenas dados fictícios locais.');
  const backend = [];
  page.on('request', request => { if (/\/api\/gifts|firestore.googleapis|identitytoolkit.googleapis|api.resend.com/.test(request.url())) backend.push(request.url()); });
  await page.goto('/#/admin/login');
  await page.getByRole('button', { name: 'Explorar painel de exemplo' }).click();
  await page.getByRole('link', { name: 'Gerenciar presentes' }).click();
  await page.getByLabel('Título do presente').fill('Panela fictícia E2E');
  await page.getByLabel('Descrição', { exact: true }).fill('Presente de teste, sem compra real.');
  await page.getByRole('button', { name: 'Salvar presente' }).click();
  await expect(page.getByRole('heading', { name: 'Panela fictícia E2E' })).toBeVisible();
  await page.getByRole('link', { name: 'Site do casamento' }).click();
  const card = page.locator('.gift-card').filter({ has: page.getByRole('heading', { name: 'Panela fictícia E2E' }) });
  await card.getByRole('button', { name: 'Escolher este presente' }).click();
  await card.getByLabel('Seu nome', { exact: true }).fill('Convidada fictícia');
  await card.getByLabel('Seu e-mail', { exact: true }).fill('ficticia@example.test');
  await card.getByRole('button', { name: 'Enviar link de confirmação' }).click();
  await expect(card.getByText('Aguardando confirmação', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Simular o link recebido por e-mail' }).click();
  await expect(page.getByRole('heading', { name: 'Confirme sua escolha' })).toBeVisible();
  expect(page.url()).toContain('token=');
  await page.getByRole('button', { name: 'Confirmar presente', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Presente confirmado!' })).toBeVisible();
  expect(page.url()).not.toContain('token=');
  await page.getByRole('link', { name: 'Lista de presentes' }).click();
  await expect(card.getByText('Já escolhido', { exact: true })).toBeVisible();
  await expect(card.getByRole('button', { name: 'Escolher este presente' })).toBeDisabled();
  await page.goto('/#/admin/presentes');
  const adminCard = page.locator('.gift-card').filter({ has: page.getByRole('heading', { name: 'Panela fictícia E2E' }) });
  await expect(page.getByRole('cell', { name: 'ficticia@example.test' })).toBeVisible();
  const accessibility = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  expect(accessibility.violations).toEqual([]);
  await adminCard.getByRole('button', { name: 'Liberar presente' }).click();
  await page.getByRole('button', { name: 'Confirmar liberação' }).click();
  await expect(adminCard.getByText('Disponível', { exact: true })).toBeVisible();
  await adminCard.getByRole('button', { name: 'Arquivar' }).click();
  await expect(adminCard.getByText('Arquivado', { exact: true })).toBeVisible();
  await page.goto('/');
  await expect(card).toHaveCount(0);
  expect(backend).toEqual([]);
});
